/** The values for a nudge message, with badge / challenge names swapped for the user's language. */
export function nudgeVars(lang: Lang, info: { vars: Record<string, string | number>; badgeId?: string; challengeId?: string }): Record<string, string | number> {
  if (info.badgeId) return { ...info.vars, name: badgeName(lang, info.badgeId, String(info.vars.name)) };
  if (info.challengeId) return { ...info.vars, title: challengeTitle(lang, info.challengeId, String(info.vars.title)).toLowerCase() };
  return info.vars;
}

